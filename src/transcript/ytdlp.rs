//! Backend 2: `yt-dlp -J` (PLAN.md, section 6.4). Use it if YouTube changes its site and the
//! Innertube backend stops working.

use std::collections::BTreeMap;

use serde::Deserialize;

use super::TrackSource;
use crate::error::FetchError;
use crate::model::{CaptionTrack, TrackKind, TrackList};
use crate::ytdlp::{YtDlp, YtDlpError};

pub(crate) struct YtDlpSource<'a> {
    ytdlp: &'a YtDlp,
    proxy: Option<&'a str>,
}

impl<'a> YtDlpSource<'a> {
    pub(crate) fn new(ytdlp: &'a YtDlp, proxy: Option<&'a str>) -> Self {
        Self { ytdlp, proxy }
    }
}

impl TrackSource for YtDlpSource<'_> {
    fn list_tracks(&mut self, video_id: &str) -> Result<TrackList, FetchError> {
        let url = format!("https://www.youtube.com/watch?v={video_id}");
        // The runner controls the retries, so yt-dlp must not retry.
        let mut args = vec![
            "-J",
            "--skip-download",
            "--no-warnings",
            "--ignore-no-formats-error",
            "--extractor-retries",
            "0",
        ];
        if let Some(proxy) = self.proxy {
            args.extend(["--proxy", proxy]);
        }
        args.extend(["--", url.as_str()]);
        match self.ytdlp.run(&args) {
            Ok(json) => parse_info(&json),
            Err(YtDlpError::Failed { stderr }) => Err(classify(&stderr)),
            Err(error @ (YtDlpError::NotFound(_) | YtDlpError::Io(_))) => {
                Err(FetchError::unexpected(error.to_string(), None))
            }
        }
    }
}

/// The part of the `yt-dlp -J` output that the tool uses.
#[derive(Debug, Deserialize)]
struct Info {
    language: Option<String>,
    upload_date: Option<String>,
    subtitles: Option<BTreeMap<String, Vec<SubtitleFormat>>>,
    automatic_captions: Option<BTreeMap<String, Vec<SubtitleFormat>>>,
}

#[derive(Debug, Deserialize)]
struct SubtitleFormat {
    ext: Option<String>,
    url: Option<String>,
    name: Option<String>,
}

fn parse_info(json: &[u8]) -> Result<TrackList, FetchError> {
    let info: Info = serde_json::from_slice(json).map_err(|error| {
        FetchError::unexpected(format!("the yt-dlp output is not valid: {error}"), None)
    })?;
    let mut tracks = Vec::new();
    for (code, formats) in info.subtitles.unwrap_or_default() {
        if code == "live_chat" {
            continue;
        }
        if let Some(format) = best_format(&formats) {
            tracks.push(track(&code, TrackKind::Manual, format));
        }
    }
    for (key, formats) in info.automatic_captions.unwrap_or_default() {
        let Some(format) = best_format(&formats) else {
            continue;
        };
        // All keys except the original tracks are translations, with "tlang" in the URL.
        let is_translation = format
            .url
            .as_deref()
            .is_some_and(|url| url.contains("tlang="));
        let code = key.strip_suffix("-orig").unwrap_or(&key);
        let duplicate = tracks.iter().any(|track: &CaptionTrack| {
            track.kind == TrackKind::AutoGenerated && track.language_code == code
        });
        if !is_translation && !duplicate {
            tracks.push(track(code, TrackKind::AutoGenerated, format));
        }
    }
    Ok(TrackList {
        tracks,
        original_language: info.language,
        upload_date: info.upload_date,
    })
}

/// The `json3` format if it is there, or else the first format with a URL. The download replaces
/// the format in the URL with `json3`.
fn best_format(formats: &[SubtitleFormat]) -> Option<&SubtitleFormat> {
    let with_url = || formats.iter().filter(|format| format.url.is_some());
    with_url()
        .find(|format| format.ext.as_deref() == Some("json3"))
        .or_else(|| with_url().next())
}

fn track(code: &str, kind: TrackKind, format: &SubtitleFormat) -> CaptionTrack {
    CaptionTrack {
        language_code: code.to_owned(),
        kind,
        name: format.name.clone().unwrap_or_else(|| code.to_owned()),
        url: format.url.clone().unwrap_or_default(),
    }
}

/// Classify the `ERROR:` text of yt-dlp (PLAN.md, section 7.5).
fn classify(stderr: &str) -> FetchError {
    let first_line = stderr.lines().next().unwrap_or(stderr).to_owned();
    let has = |text: &str| stderr.contains(text);
    if has("HTTP Error 429") {
        FetchError::RateLimited { retry_after: None }
    } else if has("not a bot") {
        FetchError::Blocked(first_line)
    } else if has("Private video")
        || has("Video unavailable")
        || has("members-only")
        || has("Join this channel")
        || has("confirm your age")
        || has("has been removed")
        || has("is not available")
    {
        FetchError::Unavailable(first_line)
    } else if has("timed out")
        || has("Connection")
        || has("HTTP Error 5")
        || has("Unable to connect")
    {
        FetchError::Transient(first_line)
    } else {
        FetchError::unexpected(format!("yt-dlp failed: {first_line}"), Some(stderr))
    }
}

#[cfg(test)]
mod tests {
    use super::{classify, parse_info};
    use crate::error::FetchError;
    use crate::model::TrackKind;
    use crate::transcript::{Reason, select_track};

    #[test]
    fn reads_the_dubbed_video_fixture() {
        let list = parse_info(include_bytes!(
            "../../tests/fixtures/ytdlp_video_dubbed.json"
        ))
        .unwrap();
        assert_eq!(list.original_language.as_deref(), Some("en-US"));
        assert_eq!(list.upload_date.as_deref(), Some("20261106"));
        let tracks: Vec<(&str, TrackKind)> = list
            .tracks
            .iter()
            .map(|track| (track.language_code.as_str(), track.kind))
            .collect();
        assert_eq!(
            tracks,
            [
                ("de", TrackKind::AutoGenerated),
                ("en", TrackKind::AutoGenerated)
            ]
        );
        let selection = select_track(&list, "en").unwrap();
        assert_eq!(selection.track.language_code, "en");
        assert_eq!(selection.reason, Reason::Original);
        assert!(selection.track.url.contains("fmt=json3"));
        assert!(!selection.track.url.contains("tlang="));
    }

    #[test]
    fn reads_manual_subtitles() {
        let json = br#"{
            "language": "pt",
            "subtitles": {
                "live_chat": [{"ext": "json", "url": "https://example.com/chat"}],
                "pt-BR": [{"ext": "vtt", "url": "https://example.com/pt?fmt=vtt", "name": "Portuguese"}]
            },
            "automatic_captions": null
        }"#;
        let list = parse_info(json).unwrap();
        assert_eq!(list.tracks.len(), 1);
        let track = &list.tracks[0];
        assert_eq!(track.language_code, "pt-BR");
        assert_eq!(track.kind, TrackKind::Manual);
        assert_eq!(track.url, "https://example.com/pt?fmt=vtt");
        assert_eq!(list.upload_date, None);
    }

    #[test]
    fn classifies_errors() {
        assert_eq!(
            classify(
                "ERROR: [youtube] x: Unable to download API page: HTTP Error 429: Too Many Requests"
            ),
            FetchError::RateLimited { retry_after: None }
        );
        assert_eq!(
            classify("ERROR: [youtube] x: Sign in to confirm you’re not a bot."),
            FetchError::Blocked(
                "ERROR: [youtube] x: Sign in to confirm you’re not a bot.".to_owned()
            )
        );
        assert_eq!(
            classify("ERROR: [youtube] x: Private video. Sign in if you've been granted access"),
            FetchError::Unavailable(
                "ERROR: [youtube] x: Private video. Sign in if you've been granted access"
                    .to_owned()
            )
        );
        assert_eq!(
            classify(
                "ERROR: [youtube] x: Unable to download webpage: The read operation timed out"
            ),
            FetchError::Transient(
                "ERROR: [youtube] x: Unable to download webpage: The read operation timed out"
                    .to_owned()
            )
        );
        let FetchError::Unexpected { message, .. } = classify("ERROR: something new") else {
            panic!("expected an unexpected-response error");
        };
        assert_eq!(message, "yt-dlp failed: ERROR: something new");
    }
}
