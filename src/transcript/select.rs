//! Track selection: the original language (PLAN.md, section 6.3).

use std::collections::BTreeSet;

use crate::model::{CaptionTrack, TrackKind, TrackList};

/// Why the tool selected a track.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Reason {
    /// The track is in the original language of the video.
    Original,
    /// The original language is not clear, and this is the only manual track.
    OnlyManualTrack,
    /// The original language is not clear. The track is in the `--lang` language.
    FallbackLanguage,
    /// The original language is not clear, and there is no track in the `--lang` language.
    FirstTrack,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Selection<'a> {
    pub(crate) track: &'a CaptionTrack,
    pub(crate) reason: Reason,
}

/// Select the track to download. `None` if there are no tracks.
pub(crate) fn select_track<'a>(list: &'a TrackList, fallback_lang: &str) -> Option<Selection<'a>> {
    let original = list
        .original_language
        .as_deref()
        .map(main_code)
        .or_else(|| single_auto_language(&list.tracks));

    if let Some(original) = original {
        let track = find(&list.tracks, TrackKind::Manual, &original)
            .or_else(|| find(&list.tracks, TrackKind::AutoGenerated, &original));
        if let Some(track) = track {
            return Some(Selection {
                track,
                reason: Reason::Original,
            });
        }
    }

    let fallback = main_code(fallback_lang);
    let manual: Vec<&CaptionTrack> = of_kind(&list.tracks, TrackKind::Manual).collect();
    if let [only] = manual.as_slice() {
        return Some(Selection {
            track: only,
            reason: Reason::OnlyManualTrack,
        });
    }
    let kind = if manual.is_empty() {
        TrackKind::AutoGenerated
    } else {
        TrackKind::Manual
    };
    if let Some(track) = find(&list.tracks, kind, &fallback) {
        return Some(Selection {
            track,
            reason: Reason::FallbackLanguage,
        });
    }
    of_kind(&list.tracks, kind).next().map(|track| Selection {
        track,
        reason: Reason::FirstTrack,
    })
}

/// The main part of a language code, in lower case: `en-US` and `en_GB` give `en`.
pub(crate) fn main_code(code: &str) -> String {
    code.split(['-', '_'])
        .next()
        .unwrap_or(code)
        .to_ascii_lowercase()
}

fn of_kind(tracks: &[CaptionTrack], kind: TrackKind) -> impl Iterator<Item = &CaptionTrack> {
    tracks.iter().filter(move |track| track.kind == kind)
}

fn find<'a>(tracks: &'a [CaptionTrack], kind: TrackKind, code: &str) -> Option<&'a CaptionTrack> {
    of_kind(tracks, kind).find(|track| main_code(&track.language_code) == code)
}

/// The language of the auto-generated tracks, if they all have the same language.
fn single_auto_language(tracks: &[CaptionTrack]) -> Option<String> {
    let languages: BTreeSet<String> = of_kind(tracks, TrackKind::AutoGenerated)
        .map(|track| main_code(&track.language_code))
        .collect();
    let mut languages = languages.into_iter();
    match (languages.next(), languages.next()) {
        (Some(language), None) => Some(language),
        (None, None) | (None, Some(_)) | (Some(_), Some(_)) => None,
    }
}

#[cfg(test)]
mod tests {
    use super::{Reason, main_code, select_track};
    use crate::model::{CaptionTrack, TrackKind, TrackList};

    fn track(code: &str, kind: TrackKind) -> CaptionTrack {
        CaptionTrack {
            language_code: code.to_owned(),
            kind,
            name: code.to_owned(),
            url: format!("https://example.com/{code}"),
        }
    }

    fn manual(code: &str) -> CaptionTrack {
        track(code, TrackKind::Manual)
    }

    fn auto(code: &str) -> CaptionTrack {
        track(code, TrackKind::AutoGenerated)
    }

    fn track_list(tracks: Vec<CaptionTrack>, original: Option<&str>) -> TrackList {
        TrackList {
            tracks,
            original_language: original.map(str::to_owned),
            upload_date: None,
        }
    }

    fn select(list: &TrackList) -> Option<(String, TrackKind, Reason)> {
        select_track(list, "en").map(|selection| {
            (
                selection.track.language_code.clone(),
                selection.track.kind,
                selection.reason,
            )
        })
    }

    #[test]
    fn main_code_drops_the_region() {
        assert_eq!(main_code("en-US"), "en");
        assert_eq!(main_code("pt_BR"), "pt");
        assert_eq!(main_code("DE"), "de");
    }

    #[test]
    fn dubbed_video_uses_the_original_audio_language() {
        let tracks = vec![auto("ar"), auto("de"), auto("en"), auto("fr")];
        let list = track_list(tracks, Some("en-US"));
        let expected = ("en".to_owned(), TrackKind::AutoGenerated, Reason::Original);
        assert_eq!(select(&list), Some(expected));
    }

    #[test]
    fn manual_track_in_the_original_language_wins() {
        let tracks = vec![auto("pt"), manual("en"), manual("pt-BR")];
        let list = track_list(tracks, Some("pt"));
        let expected = ("pt-BR".to_owned(), TrackKind::Manual, Reason::Original);
        assert_eq!(select(&list), Some(expected));
    }

    #[test]
    fn single_auto_track_gives_the_original_language() {
        let tracks = vec![manual("en"), auto("es"), manual("es-419")];
        let list = track_list(tracks, None);
        let expected = ("es-419".to_owned(), TrackKind::Manual, Reason::Original);
        assert_eq!(select(&list), Some(expected));
    }

    #[test]
    fn original_language_without_a_track_falls_back() {
        let list = track_list(vec![manual("en"), manual("de")], Some("ja"));
        let expected = ("en".to_owned(), TrackKind::Manual, Reason::FallbackLanguage);
        assert_eq!(select(&list), Some(expected));
    }

    #[test]
    fn unclear_original_with_one_manual_track() {
        let list = track_list(vec![manual("fr")], None);
        let expected = ("fr".to_owned(), TrackKind::Manual, Reason::OnlyManualTrack);
        assert_eq!(select(&list), Some(expected));
    }

    #[test]
    fn unclear_original_with_many_manual_tracks() {
        let tracks = vec![manual("fr"), manual("en-GB"), auto("fr"), auto("en")];
        let list = track_list(tracks, None);
        let expected = (
            "en-GB".to_owned(),
            TrackKind::Manual,
            Reason::FallbackLanguage,
        );
        assert_eq!(select(&list), Some(expected));

        let list = track_list(vec![manual("fr"), manual("de")], None);
        let expected = ("fr".to_owned(), TrackKind::Manual, Reason::FirstTrack);
        assert_eq!(select(&list), Some(expected));
    }

    #[test]
    fn unclear_original_with_only_auto_tracks() {
        let list = track_list(vec![auto("fr"), auto("en")], None);
        let expected = (
            "en".to_owned(),
            TrackKind::AutoGenerated,
            Reason::FallbackLanguage,
        );
        assert_eq!(select(&list), Some(expected));

        let list = track_list(vec![auto("fr"), auto("de")], None);
        let expected = (
            "fr".to_owned(),
            TrackKind::AutoGenerated,
            Reason::FirstTrack,
        );
        assert_eq!(select(&list), Some(expected));
    }

    #[test]
    fn no_tracks_gives_none() {
        assert_eq!(select(&track_list(Vec::new(), Some("en"))), None);
    }
}
