//! Data types that the modules share.

use std::time::Duration;

/// One long video of the channel, from the video list.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Video {
    pub(crate) id: String,
    pub(crate) title: String,
    pub(crate) duration: Option<Duration>,
}

impl Video {
    pub(crate) fn url(&self) -> String {
        format!("https://www.youtube.com/watch?v={}", self.id)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum TrackKind {
    /// Captions that a person made.
    Manual,
    /// Automatic speech recognition (`kind: "asr"`).
    AutoGenerated,
}

/// One caption track of a video.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct CaptionTrack {
    pub(crate) language_code: String,
    pub(crate) kind: TrackKind,
    pub(crate) name: String,
    pub(crate) url: String,
}

/// All caption tracks of a video, and the data that helps to select one.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct TrackList {
    pub(crate) tracks: Vec<CaptionTrack>,
    /// The language of the original audio track, if the source gives it (for example `en-US`).
    pub(crate) original_language: Option<String>,
    /// The upload date as `YYYYMMDD`, if the source gives it.
    pub(crate) upload_date: Option<String>,
}

/// One line of a transcript.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Segment {
    pub(crate) start: Duration,
    pub(crate) text: String,
}
